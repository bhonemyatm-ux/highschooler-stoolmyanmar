// 3) Accessible modal (focus trap + Esc + return focus) [web:16]
// =====================
(function modalSetup(){
  const modal = document.getElementById("adviceModal");
  if (!modal) return;

  const content = modal.querySelector(".modal-content");
  const closeBtn = modal.querySelector("[data-close]") || modal.querySelector(".modal-close");
  const modalGrade = document.getElementById("modalGrade");
  const modalTitle = document.getElementById("modalTitle");
  const modalSubtitle = document.getElementById("modalSubtitle");
  const modalAdviceContent = document.getElementById("modalAdviceContent");

  let lastActive = null;

  function getFocusable(container){
    return [...container.querySelectorAll(
      'a[href], button:not([disabled]), textarea, input, select, [tabindex]:not([tabindex="-1"])'
    )].filter(el => !el.hasAttribute("disabled") && el.offsetParent !== null);
  }

  function renderAdvice(level){
    const data = careerAdvice[level];
    if (!data) return;

    modalGrade.textContent = data.grade;
    modalTitle.textContent = data.title;
    modalSubtitle.textContent = data.subtitle;

    let html = "";
    data.sections.forEach(section => {
      html += `<div class="advice-section">
        <h3>${section.title}</h3>
        <ul class="advice-list">`;

      section.advice.forEach(item => {
        const { icon, text } = splitIconAndText(item);
        html += `<li><span class="advice-icon">${icon}</span>${text}</li>`;
      });

      html += `</ul></div>`;
    });

    modalAdviceContent.innerHTML = html;
  }

  function openAdvice(level, triggerEl){
    if (!careerAdvice[level]) return;

    lastActive = triggerEl || document.activeElement;
    renderAdvice(level);

    modal.classList.add("active");
    modal.setAttribute("aria-hidden", "false");
    document.body.style.overflow = "hidden";

    const focusables = getFocusable(modal);
    (focusables[0] || content).focus();
  }

  function closeAdvice(){
    modal.classList.remove("active");
    modal.setAttribute("aria-hidden", "true");
    document.body.style.overflow = "";

    if (lastActive) lastActive.focus();
  }

  document.querySelectorAll(".level-node[data-advice]").forEach(btn => {
    btn.addEventListener("click", () => openAdvice(btn.dataset.advice, btn));
  });

  if (closeBtn) closeBtn.addEventListener("click", closeAdvice);
  modal.addEventListener("click", (e) => { if (e.target === modal) closeAdvice(); });

  document.addEventListener("keydown", (e) => {
    if (!modal.classList.contains("active")) return;

    if (e.key === "Escape"){
      e.preventDefault();
      closeAdvice();
      return;
    }

    if (e.key === "Tab"){
      const focusables = getFocusable(modal);
      if (!focusables.length) return;

      const first = focusables[0];
      const last = focusables[focusables.length - 1];

      if (e.shiftKey && document.activeElement === first){
        e.preventDefault();
        last.focus();
      } else if (!e.shiftKey && document.activeElement === last){
        e.preventDefault();
        first.focus();
      }
    }
  });

  window.openAdvice = (level) => openAdvice(level, document.activeElement);
  window.closeAdvice = closeAdvice;
})();

